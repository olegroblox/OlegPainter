current_lang = "ru"

def tr(text_key, **kwargs):
    # Получаем текущий язык динамически
    try:
        # Пытаемся получить current_lang из модуля
        import sys
        if __name__ in sys.modules:
            current_lang_dynamic = sys.modules[__name__].current_lang
        else:
            current_lang_dynamic = current_lang
    except:
        current_lang_dynamic = current_lang
    
    # Получаем перевод
    translation = LANGUAGES.get(current_lang_dynamic, LANGUAGES["en"]).get(text_key, text_key)
    
    # Форматируем с параметрами, если они есть
    try:
        return translation.format(**kwargs)
    except:
        return translation


def set_language(lang_code: str) -> None:
    """Set active language; defaults back to English if code unknown."""
    global current_lang
    if not isinstance(lang_code, str):
        raise TypeError("Language code must be a string")
    lang_code = lang_code.lower()
    if lang_code not in LANGUAGES:
        raise KeyError(f"Unsupported language: {lang_code}")
    current_lang = lang_code


def get_language() -> str:
    """Return currently active language code."""
    return current_lang


def available_languages():
    """List supported language codes in preference order."""
    return list(LANGUAGES.keys())


