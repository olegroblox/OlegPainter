class I18nManager(QObject):
    """Small facade above the raw translations module with Qt signals."""

    languageChanged = Signal(str)

    def __init__(self) -> None:
        super().__init__()
        try:
            self._current = _translations.get_language()
        except Exception:
            # Fallback to module-level constant if helper unavailable
            self._current = getattr(_translations, "current_lang", "ru")

    # -- public api -------------------------------------------------
    def current_language(self) -> str:
        return self._current

    def available_languages(self) -> Iterable[str]:
        try:
            return _translations.available_languages()
        except Exception:
            return list(getattr(_translations, "LANGUAGES", {}).keys())

    def set_language(self, lang_code: str) -> None:
        lang_code = (lang_code or "").lower()
        if not lang_code:
            return
        if lang_code == self._current:
            return
        if lang_code not in getattr(_translations, "LANGUAGES", {}):
            raise KeyError(f"Unsupported language: {lang_code}")
        try:
            _translations.set_language(lang_code)
        except AttributeError:
            setattr(_translations, "current_lang", lang_code)
        self._current = lang_code
        self.languageChanged.emit(lang_code)

    def translate(self, key: str, **kwargs) -> str:
        return _translations.tr(key, **kwargs)


# shared instance + handy alias ------------------------------------
i18n = I18nManager()


def tr(key: str, **kwargs) -> str:
    return i18n.translate(key, **kwargs)


def localized(ru: str, en: str) -> str:
    """Inline pair for screen-tool hints that have no translation key."""
    return ru if str(i18n.current_language() or "ru") == "ru" else en
